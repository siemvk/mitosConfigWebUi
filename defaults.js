  function mirrorCommandForMode(cmd, targetMode) {
    if (typeof cmd !== "string") return cmd;
    if (targetMode === "select") {
      if (NORMAL_TO_SELECT[cmd]) return NORMAL_TO_SELECT[cmd];
      if (cmd.startsWith("move_")) return "extend_" + cmd.slice(5);
      return cmd;
    }
    if (targetMode === "normal") {
      if (SELECT_TO_NORMAL[cmd]) return SELECT_TO_NORMAL[cmd];
      if (cmd.startsWith("extend_")) return "move_" + cmd.slice(7);
      return cmd;
    }
    return cmd;
  }

